def test_a_hint_name_inside_a_drift_does_not_end_it():
    """講者姓名是正體，出現在漂移段落裡不能被當成「回到正體」的證據。"""
    keep = keep_terms_from("臺中市議會 市政總質詢。發言者：黃守達")
